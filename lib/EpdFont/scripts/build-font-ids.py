#!/usr/bin/env python3
"""
Python port of build-font-ids.sh
Generates src/fontIds.h by hashing the builtin font header files.
"""

import hashlib
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
FONTS_DIR = os.path.join(SCRIPT_DIR, "..", "builtinFonts")
OUTPUT_FILE = os.path.join(SCRIPT_DIR, "..", "..", "..", "src", "fontIds.h")


def font_id(*filenames):
    """Compute a signed 32-bit font ID from one or more font header files."""
    total = 0
    for fname in filenames:
        path = os.path.join(FONTS_DIR, fname)
        with open(path, "rb") as f:
            digest = hashlib.sha256(f.read()).hexdigest()
        total += int(digest, 16)
    # Same arithmetic as the Ruby version: sum % 2^32 - 2^31
    return total % (2**32) - (2**31)


