def main():
    lines = []
    lines.append("// The contents of this file are generated by ./lib/EpdFont/scripts/build-font-ids.sh (Python port)")
    lines.append("#pragma once")
    lines.append("")

    defines = []
    for macro, files in FONTS:
        # Skip groups where any file is missing
        missing = [f for f in files if not os.path.exists(os.path.join(FONTS_DIR, f))]
        if missing:
            print(f"  [skip] {macro}: missing files: {missing}", file=sys.stderr)
            continue
        fid = font_id(*files)
        lines.append(f"#define {macro} ({fid})")
        defines.append(macro)

    lines.append("")
    lines.append("// Font ID 0 is reserved as the \"not found\" sentinel.")
    lines.append("// Guard against any hash accidentally producing 0.")
    for macro in defines:
        lines.append(f'static_assert({macro} != 0, "Font ID collision with sentinel");')
    lines.append("")

    content = "\n".join(lines)

    with open(OUTPUT_FILE, "w", newline="\r\n") as f:
        f.write(content)

    print(f"Written: {OUTPUT_FILE}", file=sys.stderr)
    print(content)


if __name__ == "__main__":
    main()
